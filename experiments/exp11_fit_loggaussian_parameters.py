"""Fit log-Gaussian limiter parameters against DVM/BGK references.

This script uses the kinetic references already generated by:

  exp09_dvm_bgk_fourier.py
  exp10_dvm_bgk_couette.py

It scans (K0, sigma) for the log-Gaussian limiter and evaluates profile errors
against DVM/BGK references for:

  - Fourier temperature profile;
  - Couette velocity profile.

The goal is to determine whether the default choice K0=0.1, sigma=1.0 is
reasonable, and to provide a data-driven parameter recommendation.
"""

import sys
from pathlib import Path
sys.path.insert(0, "src")

import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
from scipy.special import erfc

OUT_DATA = Path("results/data")
OUT_FIG = Path("results/figures")
OUT_DATA.mkdir(parents=True, exist_ok=True)
OUT_FIG.mkdir(parents=True, exist_ok=True)

TCOLD = 1.0
THOT = 1.5
TWALL = 1.0
UWALL = 0.2

B_TEMP_JUMP = 2.18
A_VELOCITY_SLIP = 1.146


def wf_log(Kn, k0, sigma):
    Kn = np.asarray(Kn, dtype=float)
    return 0.5 * erfc(-np.log(Kn / k0) / (np.sqrt(2.0) * sigma))


def fourier_nsf(y):
    return TCOLD + (THOT - TCOLD) * y


def fourier_jump(y, Kn):
    return TCOLD + (THOT - TCOLD) * (y + B_TEMP_JUMP * Kn) / (1.0 + 2.0 * B_TEMP_JUMP * Kn)


def couette_nsf(y):
    return UWALL * y


def couette_slip(y, Kn):
    return UWALL * (y + A_VELOCITY_SLIP * Kn) / (1.0 + 2.0 * A_VELOCITY_SLIP * Kn)


def rel_l2(model, ref):
    return float(np.linalg.norm(model - ref) / max(np.linalg.norm(ref), 1.0e-14))


def load_refs():
    fourier_path = OUT_DATA / "exp09_dvm_bgk_fourier_reference.csv"
    couette_path = OUT_DATA / "exp10_dvm_bgk_couette_reference.csv"

    if not fourier_path.exists():
        raise FileNotFoundError(f"Missing {fourier_path}; run exp09 first.")
    if not couette_path.exists():
        raise FileNotFoundError(f"Missing {couette_path}; run exp10 first.")

    fourier = pd.read_csv(fourier_path)
    couette = pd.read_csv(couette_path)

    return fourier, couette


def evaluate_pair(fourier_ref, couette_ref, k0, sigma):
    rows = []

    for Kn in sorted(fourier_ref["Kn"].unique()):
        s = fourier_ref[fourier_ref["Kn"] == Kn].sort_values("y")
        y = s["y"].to_numpy()
        T_ref = s["T_dvm"].to_numpy()

        W = float(wf_log(Kn, k0, sigma))
        T_model = (1.0 - W) * fourier_nsf(y) + W * fourier_jump(y, Kn)

        rows.append({
            "case": "Fourier",
            "Kn": Kn,
            "K0": k0,
            "sigma": sigma,
            "Wf": W,
            "relative_profile_error": rel_l2(T_model, T_ref),
        })

    for Kn in sorted(couette_ref["Kn"].unique()):
        s = couette_ref[couette_ref["Kn"] == Kn].sort_values("y")
        y = s["y"].to_numpy()
        u_ref = s["ux_dvm"].to_numpy()

        W = float(wf_log(Kn, k0, sigma))
        u_model = (1.0 - W) * couette_nsf(y) + W * couette_slip(y, Kn)

        rows.append({
            "case": "Couette",
            "Kn": Kn,
            "K0": k0,
            "sigma": sigma,
            "Wf": W,
            "relative_profile_error": rel_l2(u_model, u_ref),
        })

    return rows


def main():
    fourier_ref, couette_ref = load_refs()

    K0_values = np.array([0.01, 0.02, 0.03, 0.05, 0.07, 0.1, 0.15, 0.2, 0.3, 0.5, 0.7, 1.0])
    sigma_values = np.array([0.25, 0.4, 0.6, 0.8, 1.0, 1.25, 1.5, 2.0, 2.5])

    all_rows = []

    for k0 in K0_values:
        for sigma in sigma_values:
            all_rows.extend(evaluate_pair(fourier_ref, couette_ref, k0, sigma))

    df = pd.DataFrame(all_rows)

    # Aggregate objectives.
    agg = (
        df.groupby(["K0", "sigma"])
        .agg(
            mean_error=("relative_profile_error", "mean"),
            max_error=("relative_profile_error", "max"),
            median_error=("relative_profile_error", "median"),
        )
        .reset_index()
    )

    by_case = (
        df.groupby(["K0", "sigma", "case"])
        .agg(mean_case_error=("relative_profile_error", "mean"))
        .reset_index()
    )

    pivot_case = by_case.pivot_table(
        index=["K0", "sigma"],
        columns="case",
        values="mean_case_error",
    ).reset_index()

    agg = agg.merge(pivot_case, on=["K0", "sigma"], how="left")

    df.to_csv(OUT_DATA / "exp11_loggaussian_parameter_fit_raw.csv", index=False)
    agg.to_csv(OUT_DATA / "exp11_loggaussian_parameter_fit_summary.csv", index=False)

    best_mean = agg.sort_values("mean_error").iloc[0]
    best_max = agg.sort_values("max_error").iloc[0]

    print("Best by mean error:")
    print(best_mean.to_string())
    print()
    print("Best by max error:")
    print(best_max.to_string())

    # Heatmap: mean error.
    heat = agg.pivot(index="sigma", columns="K0", values="mean_error")
    fig, ax = plt.subplots(figsize=(8.5, 5.4))
    im = ax.imshow(heat.values, origin="lower", aspect="auto")
    ax.set_xticks(np.arange(len(heat.columns)))
    ax.set_xticklabels([f"{x:g}" for x in heat.columns], rotation=45)
    ax.set_yticks(np.arange(len(heat.index)))
    ax.set_yticklabels([f"{x:g}" for x in heat.index])
    ax.set_xlabel(r"$K_0$")
    ax.set_ylabel(r"$\sigma$")
    ax.set_title("Mean profile error vs DVM/BGK references")
    cbar = fig.colorbar(im, ax=ax)
    cbar.set_label("mean relative error")
    fig.tight_layout()
    fig.savefig(OUT_FIG / "fig30_parameter_fit_mean_error_heatmap.png", dpi=220)
    plt.close(fig)

    # Pareto-style scatter.
    fig, ax = plt.subplots(figsize=(7.0, 5.2))
    sc = ax.scatter(
        agg["Fourier"],
        agg["Couette"],
        c=agg["mean_error"],
        s=70,
    )
    ax.set_xlabel("mean Fourier temperature error")
    ax.set_ylabel("mean Couette velocity error")
    ax.set_title("Parameter tradeoff against DVM/BGK references")
    ax.grid(True, alpha=0.25)
    cbar = fig.colorbar(sc, ax=ax)
    cbar.set_label("combined mean error")

    # Mark default and best.
    default = agg[(np.isclose(agg["K0"], 0.1)) & (np.isclose(agg["sigma"], 1.0))]
    if len(default) == 1:
        ax.scatter(default["Fourier"], default["Couette"], marker="x", s=160, label="default K0=0.1, sigma=1.0")

    ax.scatter(best_mean["Fourier"], best_mean["Couette"], marker="*", s=180, label="best mean")

    ax.legend()
    fig.tight_layout()
    fig.savefig(OUT_FIG / "fig31_parameter_fit_tradeoff.png", dpi=220)
    plt.close(fig)

    # Error curves for default vs best.
    k0_best = float(best_mean["K0"])
    sigma_best = float(best_mean["sigma"])

    selected = []
    for label, k0, sigma in [
        ("default", 0.1, 1.0),
        ("best_mean", k0_best, sigma_best),
    ]:
        tmp = pd.DataFrame(evaluate_pair(fourier_ref, couette_ref, k0, sigma))
        tmp["choice"] = label
        selected.append(tmp)

    selected = pd.concat(selected, ignore_index=True)
    selected.to_csv(OUT_DATA / "exp11_default_vs_best_errors.csv", index=False)

    fig, axes = plt.subplots(1, 2, figsize=(12.0, 4.6), sharey=True)
    for ax, case in zip(axes, ["Fourier", "Couette"]):
        s_case = selected[selected["case"] == case]
        for choice in ["default", "best_mean"]:
            s = s_case[s_case["choice"] == choice].sort_values("Kn")
            ax.loglog(s["Kn"], s["relative_profile_error"], marker="o", label=choice)
        ax.set_title(case)
        ax.set_xlabel("Kn")
        ax.grid(True, which="both", alpha=0.25)

    axes[0].set_ylabel("relative profile error vs DVM/BGK")
    axes[1].legend()
    fig.suptitle("Default vs fitted log-Gaussian parameters")
    fig.tight_layout()
    fig.savefig(OUT_FIG / "fig32_default_vs_fitted_parameters.png", dpi=220)
    plt.close(fig)

    # Weight curves.
    K = np.logspace(-4, 2, 800)
    fig, ax = plt.subplots(figsize=(7.0, 4.8))
    ax.semilogx(K, wf_log(K, 0.1, 1.0), label="default K0=0.1, sigma=1.0")
    ax.semilogx(K, wf_log(K, k0_best, sigma_best), label=f"best mean K0={k0_best:g}, sigma={sigma_best:g}")
    ax.set_xlabel("Kn")
    ax.set_ylabel(r"$W_f$")
    ax.set_title("Default and fitted log-Gaussian weights")
    ax.grid(True, which="both", alpha=0.25)
    ax.legend()
    fig.tight_layout()
    fig.savefig(OUT_FIG / "fig33_default_vs_fitted_weights.png", dpi=220)
    plt.close(fig)

    print("Wrote:")
    print("  results/data/exp11_loggaussian_parameter_fit_raw.csv")
    print("  results/data/exp11_loggaussian_parameter_fit_summary.csv")
    print("  results/data/exp11_default_vs_best_errors.csv")
    print("  results/figures/fig30_parameter_fit_mean_error_heatmap.png")
    print("  results/figures/fig31_parameter_fit_tradeoff.png")
    print("  results/figures/fig32_default_vs_fitted_parameters.png")
    print("  results/figures/fig33_default_vs_fitted_weights.png")


if __name__ == "__main__":
    main()
